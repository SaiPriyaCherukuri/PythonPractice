print('Basic Arithmetic')

a = 10
b = 3
print('Addition : ', a + b)            # 13
print('Subtraction : ', a - b)         # 7
print('Multiplication : ', a * b)      # 30
print('Division (float) : ', a / b)    # 3.3333333333333335
print('Division (floor) : ', a // b)   # 3
print('Modulus : ', a % b)             # 1
print('Exponent : ', a ** b)           # 1000
